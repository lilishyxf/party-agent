export function getHelpContent(pathname) {
  const parts = pathname.split('/').filter(Boolean)
  const fullKey = parts.join('/')
  const moduleKey = parts[0] || 'ai'

  // Exact match first, then module-level fallback
  if (MODULE_INTROS[fullKey]) return MODULE_INTROS[fullKey]
  if (MODULE_INTROS[moduleKey]) return MODULE_INTROS[moduleKey]

  return {
    title: '使用帮助',
    sections: [{ heading: '提示', text: '该页面暂无帮助内容，如需协助请联系管理员。' }],
  }
}
